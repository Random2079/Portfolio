def build_phrases() -> list[str]:
    phrases: set[str] = set()
    verbs = MUTE_VERBS + UNMUTE_VERBS
    for v in verbs:
        phrases.add(v)
    for s in SLOTS:
        phrases.add(s)
    for t in TARGETS:
        phrases.add(t)
    for v in verbs:
        for s in SLOTS:
            phrases.add(f"{v} {s}")
        for t in TARGETS:
            phrases.add(f"{v} {t}")
    for n in range(1, 13):
        d = str(n)
        phrases.add(d)
        for v in verbs:
            phrases.add(f"{v} {d}")
    for vv in VOLUME_VERBS:
        phrases.add(vv)
        for a in VOLUME_AMOUNTS:
            phrases.add(f"{vv} на {a}")
            phrases.add(f"{vv} {a}")
            for s in SLOTS:
                phrases.add(f"{vv} на {a} {s}")
                phrases.add(f"{vv} {a} {s}")
            for t in TARGETS:
                phrases.add(f"{vv} на {a} {t}")
                phrases.add(f"{vv} {a} {t}")
    return sorted(phrases)


def grammar_json() -> str:
    return json.dumps(build_phrases(), ensure_ascii=False)
